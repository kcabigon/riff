function hexToRgba(hex: string, alpha: number): string {
  const value = parseInt(hex.replace("#", ""), 16);
  const r = (value >> 16) & 255;
  const g = (value >> 8) & 255;
  const b = value & 255;
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

// On the Avatar size scale — big enough to sit level with a two-line
// bubble without outweighing it.
const QUIP_AVATAR_SIZE = 56;

// Sizing shared by all three panel CTAs — bigger than CTAButton's own
// default so it reads as a hero action, not an inline one. Weight is left
// at CTAButton's default (300, the design system's standard button weight).
const panelButtonStyle = {
  padding: "16px 36px",
  fontSize: "17px",
};

interface MyRiffsEmptyStateProps {
  onStartWriting: () => void;
  isCreatingDraft: boolean;
}

export default function MyRiffsEmptyState({
  onStartWriting,
  isCreatingDraft,
}: MyRiffsEmptyStateProps) {
  const [hoveredPanelId, setHoveredPanelId] = useState<Panel["id"] | null>(
    null
  );
  // Touch screens can't hover, so there each bubble pops in the first time
  // its card scrolls into view instead — like a message arriving — and
  // stays. Keyed on hover capability, not width, so tablets and touch
  // laptops get it too.
  const isTouch = useMediaQuery("(hover: none)");
  const panelsRef = useRef<HTMLDivElement>(null);
  const [arrivedPanelIds, setArrivedPanelIds] = useState<Set<Panel["id"]>>(
    () => new Set()
  );

  // Nothing arrives until the first scroll, so the page opens clean and the
  // first bubble lands as a response to the reader moving. A page too short
  // to scroll starts right away — otherwise its bubbles would never show.
  const [hasScrolled, setHasScrolled] = useState(false);

  useEffect(() => {
    if (!isTouch || hasScrolled) return;
    const canScroll =
      document.documentElement.scrollHeight > window.innerHeight;
    if (!canScroll) {
      setHasScrolled(true);
      return;
    }
    const start = () => setHasScrolled(true);
    window.addEventListener("scroll", start, { passive: true, once: true });
    window.addEventListener("touchmove", start, { passive: true, once: true });
    return () => {
      window.removeEventListener("scroll", start);
      window.removeEventListener("touchmove", start);
    };
  }, [isTouch, hasScrolled]);

  useEffect(() => {
    if (!isTouch || !hasScrolled || !panelsRef.current) return;
    const cards =
      panelsRef.current.querySelectorAll<HTMLElement>("[data-panel-id]");
    const observer = new IntersectionObserver(
      (entries) => {
        const arrived = entries
          .filter((entry) => entry.isIntersecting)
          .map((entry) => (entry.target as HTMLElement).dataset.panelId);
        if (arrived.length === 0) return;
        setArrivedPanelIds((prev) => {
          const next = new Set(prev);
          arrived.forEach((id) => next.add(id as Panel["id"]));
          return next;
        });
        entries
          .filter((entry) => entry.isIntersecting)
          .forEach((entry) => observer.unobserve(entry.target));
      },
      { threshold: 0.6 }
    );
    cards.forEach((card) => observer.observe(card));
    return () => observer.disconnect();
  }, [isTouch, hasScrolled]);

  const isQuipShown = (id: Panel["id"]) =>
    isTouch ? arrivedPanelIds.has(id) : hoveredPanelId === id;
  const riffOverlay = useCreationOverlay(riffCreatedPath);
  const clubOverlay = useCreationOverlay(clubCreatedPath);

  return (
    <div
      style={{
        position: "relative",
        overflow: "hidden",
        minHeight: "calc(100vh - 70px)",
        display: "flex",
        flexDirection: "column",
        alignItems: "center",
        justifyContent: "center",
        padding: "64px 24px 96px",
        boxSizing: "border-box",
      }}
    >
      {/* Absolutely filled to match the panel's own bounds (not a fixed
          100vh) so it always covers the full container even when the
          panels stack taller than one screen on mobile — no gap to scroll
          into below it. */}
      <div aria-hidden style={{ position: "absolute", inset: 0 }}>
        <Image
          src="/images/about/friendsgiving2025.gif"
          alt=""
          fill
          unoptimized
          priority
          style={{
            objectFit: "cover",
            // Soft enough to keep faces unrecognizable without losing the
            // shapes/colors of the scene. Scaled up slightly so blur doesn't
            // soften the image's own edges into a visible halo.
            filter: "blur(4px)",
            transform: "scale(1.05)",
          }}
        />
        <div
          style={{
            position: "absolute",
            inset: 0,
            backgroundColor: "rgba(0, 0, 0, 0.85)",
          }}
        />
      </div>

      <NoiseBackground fillMode="cover" style={{ opacity: 0.15 }} />

      {/* Sized down hard on mobile via the .hero-heading media query below
          (not a JS isMobile check) — at the desktop size this wrapped to
          4-5 lines on a narrow screen and pushed every card below the
          fold. Smaller size + tighter margin leaves room for about 1.5
          cards to peek in under the hero. CSS avoids the flash-of-wrong-size
          a JS viewport check would cause pre-hydration. */}
      <h1
        className="hero-heading"
        style={{
          position: "relative",
          zIndex: 1,
          fontFamily: "var(--font-dm-serif-text)",
          fontWeight: 400,
          lineHeight: 0.98,
          letterSpacing: "-0.01em",
          color: "#FFFFFF",
          textAlign: "center",
        }}
      >
        Write with friends,{" "}
        <span style={{ fontStyle: "italic" }}>for fun.</span>
      </h1>

      <div
        ref={panelsRef}
        className="panels"
        style={{
          position: "relative",
          zIndex: 1,
          width: "100%",
          maxWidth: "1000px",
          display: "flex",
          alignItems: "center",
        }}
      >
        {PANELS.map((panel) => (
          <div
            key={panel.id}
            className="panel-slot"
            style={
              {
                flex: 1,
                display: "flex",
                justifyContent: "center",
                "--panel-rotate": `${panel.rotate}deg`,
                "--panel-lift": `${panel.lift}px`,
              } as React.CSSProperties
            }
          >
            {/* Semi-transparent "sticker card" — a black scrim (legibility)
                plus a thin wash of the panel's own accent (identity), so
                the trio reads as three placed objects instead of text
                floating loose on the photo. Shadow turns the panel's accent
                color on hover — a preview of the CTA's own hover color. */}
            <div
              data-panel-id={panel.id}
              onMouseEnter={() => setHoveredPanelId(panel.id)}
              onMouseLeave={() => setHoveredPanelId(null)}
              style={{
                position: "relative",
                width: "100%",
                maxWidth: "252px",
                aspectRatio: "4 / 5",
                boxSizing: "border-box",
                padding: "36px 24px 28px",
                display: "flex",
                flexDirection: "column",
                alignItems: "center",
                justifyContent: "center",
                gap: "20px",
                textAlign: "center",
                border: "2px solid #000000",
                boxShadow: `8px 8px 0px 0px ${
                  hoveredPanelId === panel.id ? panel.accentColor : "#000000"
                }`,
                transition: "box-shadow 0.1s ease",
              }}
            >
              {/* Group-chat message — who'd send this text, then the
                  bubble. The bubble is the one deliberately rounded shape in
                  this build: a speech bubble reads as one via its curve +
                  tail, so the brutalist "no radius" rule gets a one-off
                  exception here. */}
              <div
                aria-hidden
                style={{
                  position: "absolute",
                  bottom: "100%",
                  left: "50%",
                  marginBottom: "16px",
                  zIndex: 3,
                  width: "max-content",
                  display: "flex",
                  alignItems: "flex-end",
                  gap: "10px",
                  opacity: isQuipShown(panel.id) ? 1 : 0,
                  transform: `translateX(-50%) rotate(${panel.quipRotate}deg) translateY(${
                    isQuipShown(panel.id) ? 0 : 8
                  }px)`,
                  // Slower on touch, where it plays once as the card
                  // arrives rather than tracking a cursor.
                  transition: isTouch
                    ? "opacity 0.3s ease, transform 0.3s ease"
                    : "opacity 0.15s ease, transform 0.15s ease",
                  pointerEvents: "none",
                }}
              >
                <Avatar
                  user={{
                    id: panel.id,
                    name: panel.quipFrom.name,
                    username: null,
                    avatarUrl: panel.quipFrom.avatarSrc,
                  }}
                  size={QUIP_AVATAR_SIZE}
                />
                <div
                  style={{
                    position: "relative",
                    maxWidth: "200px",
                    padding: "12px 16px",
                    backgroundColor: "#FFFFFF",
                    border: "3px solid #000000",
                    borderRadius: "20px",
                    boxShadow: `4px 4px 0px 0px ${panel.accentColor}`,
                  }}
                >
                  <p
                    style={{
                      fontFamily: "var(--font-dm-sans)",
                      fontWeight: 700,
                      fontSize: "13px",
                      lineHeight: 1.4,
                      color: "#000000",
                      textAlign: "left",
                      margin: 0,
                    }}
                  >
                    {panel.quip}
                  </p>
                  {/* Tail on the bottom-left, pointing at the sender. */}
                  <div
                    style={{
                      position: "absolute",
                      bottom: "-9px",
                      left: "14px",
                      transform: "rotate(45deg)",
                      width: "16px",
                      height: "16px",
                      backgroundColor: "#FFFFFF",
                      borderRight: "3px solid #000000",
                      borderBottom: "3px solid #000000",
                    }}
                  />
                </div>
              </div>

              <div
                aria-hidden
                style={{
                  position: "absolute",
                  inset: 0,
                  backgroundColor: "rgba(0, 0, 0, 0.45)",
                }}
              />
              <div
                aria-hidden
                style={{
                  position: "absolute",
                  inset: 0,
                  backgroundColor: hexToRgba(panel.accentColor, 0.16),
                  mixBlendMode: "screen",
                }}
              />

              <div
                style={{
                  position: "relative",
                  zIndex: 1,
                  display: "flex",
                  flexDirection: "column",
                  alignItems: "center",
                  gap: "32px",
                }}
              >
                <div
                  style={{
                    display: "flex",
                    flexDirection: "column",
                    gap: "12px",
                  }}
                >
                  <h2
                    style={{
                      fontFamily: "var(--font-dm-serif-text)",
                      fontSize: "32px",
                      fontWeight: 400,
                      lineHeight: 1.2,
                      color: "#FFFFFF",
                      margin: 0,
                    }}
                  >
                    {panel.heading}
                  </h2>
                  <p
                    style={{
                      fontFamily: "var(--font-dm-sans)",
                      fontSize: "16px",
                      fontWeight: 300,
                      lineHeight: 1.6,
                      color: "rgba(255, 255, 255, 0.8)",
                      margin: 0,
                    }}
                  >
                    {panel.body}
                  </p>
                </div>

                {panel.id === "write" && (
                  <CTAButton
                    accentColor={panel.accentColor}
                    onClick={onStartWriting}
                    style={panelButtonStyle}
                  >
                    {isCreatingDraft ? "Creating…" : panel.cta}
                  </CTAButton>
                )}

                {panel.id === "riff" && (
                  <CTAButton
                    accentColor={panel.accentColor}
                    onClick={riffOverlay.open}
                    style={panelButtonStyle}
                  >
                    {panel.cta}
                  </CTAButton>
                )}

                {panel.id === "club" && (
                  <CTAButton
                    accentColor={panel.accentColor}
                    onClick={clubOverlay.open}
                    style={panelButtonStyle}
                  >
                    {panel.cta}
                  </CTAButton>
                )}
              </div>
            </div>
          </div>
        ))}
      </div>

      <style>{`
        /* Stacked, each card needs room above it for its bubble (~66px
           tall + 16px offset) — the gap between cards, plus padding over
           the first one so its bubble clears the heading. Padding + the
           heading's 32px margin = 112px, the same as the gap between
           cards, so the whole stack keeps one rhythm. */
        .panels {
          flex-direction: column;
          gap: 112px;
          padding-top: 80px;
        }
        /* The lift staggers the cards' heights side by side; stacked, it
           would just make the gaps between them uneven, so it's desktop
           only. */
        .panel-slot {
          transform: rotate(var(--panel-rotate));
        }
        .hero-heading {
          font-size: 64px;
          margin: 0 0 32px 0;
          max-width: 300px;
        }
        @media (min-width: 768px) {
          .panels {
            flex-direction: row;
            align-items: flex-start;
            gap: 56px;
            padding-top: 24px;
          }
          .panel-slot {
            transform: rotate(var(--panel-rotate))
              translateY(var(--panel-lift));
          }
          .hero-heading {
            font-size: 80px;
            margin: 0 0 80px 0;
            max-width: 750px;
          }
        }
      `}</style>

      <CreateRiffOverlay
        isOpen={riffOverlay.isOpen}
        onClose={riffOverlay.close}
        onCreated={riffOverlay.onCreated}
      />
      <CreateClubOverlay
        isOpen={clubOverlay.isOpen}
        onClose={clubOverlay.close}
        onCreated={clubOverlay.onCreated}
      />
    </div>
  );
}
