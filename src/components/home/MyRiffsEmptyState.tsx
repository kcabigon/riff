"use client";

import { useState } from "react";
import { useRouter, usePathname } from "next/navigation";
import NoiseBackground from "@/components/NoiseBackground";

type Shape = "bolt" | "triangle" | "circle";

interface Panel {
  id: "write" | "riff" | "club";
  lines: [string, string];
  cta: string;
  accentColor: string;
  shapeColor: string;
  rotate: number;
  lift: number;
  shape: Shape;
  wobbleDuration: number;
  wobbleDelay: number;
}

// The three domains as a ladder — write alone, riff with friends, club as
// the recurring version of that, left to right. Each is a stamped,
// slightly-off-kilter "sticker" rather than a perfectly aligned card, so
// the trio reads as placed by hand rather than generated by a grid.
